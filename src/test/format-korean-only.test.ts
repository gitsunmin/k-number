describe('[format] => korean-only — 일 생략 규칙 (국립국어원 표준)', () => {
  test('10 -> 십 (일십 아님)', () => {
    expect(kNumber(10)).toBe('십');
  });

  test('100 -> 백 (일백 아님)', () => {
    expect(kNumber(100)).toBe('백');
  });

  test('1_000 -> 천 (일천 아님)', () => {
    expect(kNumber(1_000)).toBe('천');
  });

  test('10_000 -> 일만 (만 앞 일 유지)', () => {
    expect(kNumber(10_000)).toBe('일만');
  });

  test('100_000_000 -> 일억 (억 앞 일 유지)', () => {
    expect(kNumber(100_000_000)).toBe('일억');
  });

  test('1_000_000_000_000 -> 일조 (조 앞 일 유지)', () => {
    expect(kNumber(1_000_000_000_000)).toBe('일조');
  });

  test('11 -> 십일', () => {
    expect(kNumber(11)).toBe('십일');
  });

  test('110 -> 백십', () => {
    expect(kNumber(110)).toBe('백십');
  });

  test('1_100 -> 천백', () => {
    expect(kNumber(1_100)).toBe('천백');
  });

  test('1_001 -> 천일', () => {
    expect(kNumber(1_001)).toBe('천일');
  });

  test('1_010 -> 천십', () => {
    expect(kNumber(1_010)).toBe('천십');
  });

  test('1_000_000 -> 백만 (천만 그룹 내 백 자리 1 → 생략)', () => {
    expect(kNumber(1_000_000)).toBe('백만');
  });

  test('10_000_000 -> 천만 (천만 그룹 내 천 자리 1 → 생략)', () => {
    expect(kNumber(10_000_000)).toBe('천만');
  });

  test('11_000_000 -> 천백만', () => {
    expect(kNumber(11_000_000)).toBe('천백만');
  });

  test('-1_000 -> -천', () => {
    expect(kNumber(-1_000)).toBe('-천');
  });

  test('-10_000 -> -일만', () => {
    expect(kNumber(-10_000)).toBe('-일만');
  });
});
